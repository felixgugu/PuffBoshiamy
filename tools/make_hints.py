#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build a Lua hint table: char -> { short = shortest boshiamy code,
full = longest boshiamy code }.

The source is the same CIN/LIME table used by tools/lime2rime.py.  The table
does not label which code is an official short code; we derive:

    short = shortest code in the table
    full  = longest code in the table (earliest entry on ties)

Usage:
    python tools/make_hints.py
    python tools/make_hints.py --input data/boshiamy.lime
"""

from __future__ import annotations

import argparse
import collections
import io
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lime2rime import BOSHIAMY_CODE_RE, read_source  # noqa: E402


def build_hints(source: Path):
    entries, fmt = read_source(source)
    by_char = collections.defaultdict(list)
    order = 0
    bad = 0
    for code, text, _lineno in entries:
        if not BOSHIAMY_CODE_RE.match(code) or len(text) != 1:
            bad += 1
            continue
        by_char[text].append((order, code))
        order += 1

    hints = {}
    for text, items in by_char.items():
        short = min(items, key=lambda x: (len(x[1]), x[0]))[1]
        full = min(items, key=lambda x: (-len(x[1]), x[0]))[1]
        hints[text] = (short, full)
    return hints, fmt, bad


def build_prefixes(source: Path):
    """Return the set of all code prefixes (including complete codes)."""
    entries, fmt = read_source(source)
    codes = set()
    for code, _text, _lineno in entries:
        if BOSHIAMY_CODE_RE.match(code):
            codes.add(code)
    prefixes = set()
    for code in codes:
        for i in range(1, len(code) + 1):
            prefixes.add(code[:i])
    return prefixes, fmt, len(codes)


def read_essay(path: Path):
    """Return {text: frequency} from Rime's essay.txt."""
    freq = {}
    if not path.exists():
        return freq
    for line in path.read_text(encoding="utf-8").splitlines():
        if "\t" not in line:
            continue
        text, weight = line.split("\t", 1)
        try:
            freq[text] = int(weight)
        except ValueError:
            pass
    return freq


def build_completion(entries, freq):
    """Return prefix -> [(character, shortest matching code)] by frequency.

    Exact-code candidates are left to the main table translator, so they are
    excluded here.  This is what lets the completion list order characters by
    common usage instead of librime's built-in code-length order.

    The code hint is the shortest code for that character which starts with
    the prefix.  Showing the character's global shortest code would be
    confusing: e.g. 或 has the short code `he` but appears under `a` because
    of `aqoe`.
    """
    codes_by_text = collections.defaultdict(list)
    first_order = {}
    for order, (code, text, _lineno) in enumerate(entries):
        if not BOSHIAMY_CODE_RE.match(code) or len(text) != 1:
            continue
        if code not in codes_by_text[text]:
            codes_by_text[text].append(code)
        first_order.setdefault(text, order)

    by_prefix = collections.defaultdict(set)
    for code, text, _lineno in entries:
        if not BOSHIAMY_CODE_RE.match(code) or len(text) != 1:
            continue
        for i in range(1, len(code) + 1):
            prefix = code[:i]
            # A character with an exact code for this prefix is already
            # provided by the main table translator.
            if prefix in codes_by_text[text]:
                continue
            by_prefix[prefix].add(text)

    result = {}
    for prefix, texts in by_prefix.items():
        ordered = sorted(texts, key=lambda t: (-freq.get(t, 0), first_order[t]))
        result[prefix] = [
            (text, min((c for c in codes_by_text[text] if c.startswith(prefix)),
                       key=lambda c: (len(c), codes_by_text[text].index(c))))
            for text in ordered
        ]
    return result


def lua_quote(s: str) -> str:
    return ('"' + s.replace("\\", "\\\\").replace('"', '\\"')
            .replace("\n", "\\n").replace("\r", "\\r")
            .replace("\t", "\\t") + '"')


def write_prefixes(prefixes, output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    out = io.StringIO()
    out.write("-- Generated by tools/make_hints.py.  Do not edit.\n")
    out.write("-- All boshiamy code prefixes; used by boshiamy_v.lua.\n")
    out.write("return {\n")
    for code in sorted(prefixes):
        out.write(f"  [{lua_quote(code)}] = true,\n")
    out.write("}\n")
    output.write_text(out.getvalue(), encoding="utf-8")


def write_lua(hints, output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    out = io.StringIO()
    out.write("-- Generated by tools/make_hints.py.  Do not edit.\n")
    out.write("return {\n")
    for text in sorted(hints):
        short, full = hints[text]
        out.write(f"  [{lua_quote(text)}] = {{ short = {lua_quote(short)}, "
                  f"full = {lua_quote(full)} }},\n")
    out.write("}\n")
    output.write_text(out.getvalue(), encoding="utf-8")


def write_completion_lua(by_prefix, output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    out = io.StringIO()
    out.write("-- Generated by tools/make_hints.py.  Do not edit.\n")
    out.write("-- prefix -> characters sorted by essay frequency.\n")
    out.write("-- Exact-code characters are handled by the main table\n")
    out.write("-- translator and are excluded here.\n")
    out.write("return {\n")
    for prefix in sorted(by_prefix):
        records = "".join(f"{text}\t{code}\n" for text, code in by_prefix[prefix])
        out.write(f"  [{lua_quote(prefix)}] = {lua_quote(records)},\n")
    out.write("}\n")
    output.write_text(out.getvalue(), encoding="utf-8")


def write_report(hints, prefixes, completion, code_count, source: Path, fmt: str, bad: int,
                 output: Path) -> None:
    out = io.StringIO()
    w = lambda *a: print(*a, file=out)
    w("# boshiamy hints report")
    w(f"source: {source} ({fmt})")
    w(f"chars: {len(hints)}  codes: {code_count}  prefixes: {len(prefixes)}  skipped entries: {bad}")
    w(f"completion prefixes: {len(completion)}  "
      f"entries: {sum(len(v) for v in completion.values())}")
    w(f"akv is prefix: {'akv' in prefixes}  av is prefix: {'av' in prefixes}")
    same = sum(1 for s, f in hints.values() if s == f)
    w(f"chars where short == full: {same}")
    w("short length distribution: " + ", ".join(
        f"{n}:{sum(1 for s, _f in hints.values() if len(s) == n)}" for n in range(1, 7)))
    w("full length distribution: " + ", ".join(
        f"{n}:{sum(1 for _s, f in hints.values() if len(f) == n)}" for n in range(1, 7)))
    w("samples:")
    for ch in ["對", "你", "我", "是", "的", "中", "國", "好", "天", "一", "的", "𠮷"]:
        if ch in hints:
            s, f = hints[ch]
            w(f"  {ch}: short={s} full={f}")
    w("first 20 chars: " + ", ".join(
        f"{c}={hints[c][0]}/{hints[c][1]}" for c in sorted(hints)[:20]))
    for prefix in ("i", "a", "aa", "aaa"):
        if prefix in completion:
            w(f"completion[{prefix}]: " +
              " ".join(f"{text}({code})" for text, code in completion[prefix][:20]))
        else:
            w(f"completion[{prefix}]: (none)")
    output.parent.joinpath("hints-report.txt").write_text(out.getvalue(), encoding="utf-8")


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=None)
    parser.add_argument("--output", type=Path, default=root / "dist" / "lua" / "boshiamy_hints.lua")
    parser.add_argument("--prefix-output", type=Path,
                        default=root / "dist" / "lua" / "boshiamy_prefixes.lua")
    parser.add_argument("--completion-output", type=Path,
                        default=root / "dist" / "lua" / "boshiamy_completion_data.lua")
    parser.add_argument("--essay", type=Path, default=root / "data" / "essay.txt")
    args = parser.parse_args()

    source = args.input
    if source is None:
        for candidate in (root / "data" / "liu7.cin", root / "data" / "boshiamy.lime"):
            if candidate.exists():
                source = candidate
                break
    if source is None:
        raise SystemExit("no source table found")

    hints, fmt, bad = build_hints(source)
    prefixes, prefix_fmt, code_count = build_prefixes(source)
    entries, _ = read_source(source)
    completion = build_completion(entries, read_essay(args.essay))
    write_lua(hints, args.output)
    write_prefixes(prefixes, args.prefix_output)
    write_completion_lua(completion, args.completion_output)
    write_report(hints, prefixes, completion, code_count, source, fmt, bad, args.output)
    print(f"source: {source.name} ({fmt})  chars: {len(hints)}  "
          f"codes: {code_count}  prefixes: {len(prefixes)}  "
          f"completion: {len(completion)}  skipped: {bad}  output: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
