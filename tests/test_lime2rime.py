#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Tests for tools/lime2rime.py."""

import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import lime2rime  # noqa: E402


class TestLime2Rime(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.source = ROOT / "data" / "boshiamy.lime"
        cls.entries = lime2rime.read_lime(cls.source)
        cls.data = lime2rime.build(cls.entries)

    def test_entry_counts(self):
        self.assertEqual(len(self.entries), 41492)
        self.assertEqual(len(self.data["rows"]), 41476)
        self.assertEqual(len(self.data["by_code"]), 27248)
        self.assertEqual(len(self.data["invalid_codes"]), 0)
        self.assertEqual(len(self.data["invalid_texts"]), 0)
        self.assertEqual(len(self.data["malformed"]), 0)

    def test_a_candidates_keep_source_order(self):
        got = [text for text, _lineno in self.data["by_code"]["a"]]
        self.assertEqual(got, ["對", "夺", "对", "対"])

    def test_bom_stripped(self):
        for code, text, _lineno in self.entries:
            self.assertNotIn("\ufeff", code)
            self.assertNotIn("\ufeff", text)

    def test_codes_and_texts(self):
        for code, text, _lineno in self.entries:
            if code.startswith("#"):
                continue
            self.assertRegex(code, r"^[a-z,.\[\]']+$")
            self.assertEqual(len(text), 1)

    def test_weights_strictly_decreasing(self):
        rows = self.data["rows"]
        self.assertEqual(len({w for _c, _t, w in rows}), len(rows))
        for prev, cur in zip(rows, rows[1:]):
            self.assertGreater(prev[2], cur[2])

    def test_pua_count(self):
        self.assertEqual(len(self.data["pua"]), 20)

    def test_dist_file_if_built(self):
        dist = ROOT / "dist" / "puffime.dict.yaml"
        if not dist.exists():
            self.skipTest("dist not built")
        text = dist.read_text(encoding="utf-8")
        lines = [ln for ln in text.splitlines() if "\t" in ln]
        self.assertTrue(lines)
        self.assertIn("# Generated by tools/lime2rime.py from", text)
        self.assertTrue(any(ln.startswith("對\ta\t") for ln in lines))
        self.assertTrue(any(ln.startswith("寸\taa\t") for ln in lines))

    def test_cin_source(self):
        path = ROOT / "data" / "liu7.cin"
        if not path.exists():
            self.skipTest("liu7.cin not present")
        entries, fmt = lime2rime.read_source(path)
        self.assertEqual(fmt, "cin")
        self.assertEqual(len(entries), 31556)
        data = lime2rime.build(entries)
        self.assertEqual(len(data["by_code"]), 22778)
        self.assertEqual([t for t, _ln in data["by_code"]["a"]], ["對"])
        self.assertEqual(data["by_code"]["yneu"][0][0], "殼")
        self.assertEqual(len(data["pua"]), 0)
        self.assertEqual(len(data["invalid_codes"]), 0)


if __name__ == "__main__":
    unittest.main()
